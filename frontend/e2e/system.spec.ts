test('loading latest progress restores a newer assessment attempt', async ({ page }) => {
  await register(page)
  await page.locator('input[type=file]').setInputFiles({ name: 'Latest lesson.txt', mimeType: 'text/plain', buffer: Buffer.from(lesson) })
  await page.getByLabel('Select Latest lesson.txt').check()
  await page.getByRole('button', { name: /Open workspace/ }).click()
  await page.getByRole('tab', { name: 'Quiz', exact: true }).click()
  await page.getByLabel('Number of questions').fill('3')
  await page.getByRole('button', { name: 'Generate quiz', exact: true }).click()
  await page.getByRole('button', { name: 'Begin quiz', exact: true }).click()
  await page.getByRole('button', { name: 'A Oxygen' }).click()
  await page.getByRole('button', { name: 'Check answer', exact: true }).click()
  await expect(page.locator('.assessment .save-status')).toContainText('Saved')
  const remote = await page.evaluate(async () => {
    const me = await (await fetch('/api/auth/me')).json(), rows = await (await fetch('/api/attempts')).json(), old = rows[0]
    const headers = { 'Content-Type': 'application/json', 'X-CSRF-Token': me.csrf }
    await fetch(`/api/attempts/${old.id}/submit`, { method: 'POST', headers })
    const fresh = await (await fetch('/api/attempts', { method: 'POST', headers, body: JSON.stringify({ study_set_id: old.study_set_id }) })).json()
    const path = `/api/study-sets/${old.study_set_id}/progress`, state = await (await fetch(path)).json()
    return (await fetch(path, { method: 'PUT', headers, body: JSON.stringify({ version: state.version, data: { attempt_id: fresh.id, index: 1 } }) })).status
  })
  expect(remote).toBe(200)
  await page.getByRole('button', { name: 'Next question' }).click()
  await expect(page.locator('.assessment .save-status')).toContainText('Updated on another device')
  await page.getByRole('button', { name: 'Load latest', exact: true }).click()
  await expect(page.getByText('Question 2 of 3', { exact: true })).toBeVisible()
  await expect(page.getByText('0 answered', { exact: true })).toBeVisible()
})

